#!/usr/bin/env python3
"""Merge the per-implementation replay TSVs into one comparison table.

Emits a LaTeX table for the report and a readable summary for the
terminal. Rows where every implementation agrees are collapsed unless
--all is given, since the interesting rows are the ones that diverge.
"""
import argparse
import glob
import os
import pathlib


def load(path):
    rows = {}
    for line in pathlib.Path(path).read_text().splitlines():
        parts = line.split("\t")
        if len(parts) >= 2:
            rows[parts[0]] = (parts[1], parts[2] if len(parts) > 2 else "")
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true",
                    help="include rows where all implementations agree")
    ap.add_argument("--tex", default="replay_table.tex")
    args = ap.parse_args()

    files = sorted(glob.glob("replay_*.tsv"))
    if not files:
        print("no replay_*.tsv found -- run run_replay.sh first")
        return 1

    cols = [os.path.basename(f)[len("replay_"):-len(".tsv")] for f in files]
    data = [load(f) for f in files]
    names = sorted({n for d in data for n in d})

    print(f"{'input':34}" + "".join(f"{c:16}" for c in cols))
    print("-" * (34 + 16 * len(cols)))

    diverging = []
    for n in names:
        vals = [d.get(n, ("--", ""))[0] for d in data]
        if len(set(vals)) > 1:
            diverging.append(n)
        if args.all or len(set(vals)) > 1:
            print(f"{n:34}" + "".join(f"{v:16}" for v in vals))

    print()
    print(f"{len(names)} inputs, {len(diverging)} diverge across "
          f"{len(cols)} configurations")

    out = pathlib.Path(args.tex)
    with out.open("w") as fh:
        fh.write("% generated by merge_replay.py\n")
        fh.write("\\begin{table}[t]\n\\centering\\small\n")
        fh.write("\\caption{Shared inputs replayed against both "
                 "implementations.}\n\\label{tab:replay-shared}\n")
        fh.write("\\begin{tabular}{l" + "l" * len(cols) + "}\n\\toprule\n")
        fh.write("Input & " + " & ".join(
            c.replace("_", "\\_") for c in cols) + " \\\\\n\\midrule\n")
        for n in (names if args.all else diverging):
            vals = [d.get(n, ("--", ""))[0] for d in data]
            label = n.split("/")[-1].replace(".bin", "").replace("_", "\\_")
            fh.write(label + " & " + " & ".join(vals) + " \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
